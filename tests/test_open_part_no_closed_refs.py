"""В открытой части нет ссылок на закрытую кухню (FR-106).

Репозиторий увидит человек, у которого нет ни автора рядом, ни закрытых записей проекта. Номера находок, решений и допущений, номера порций
работ и номера тест-кейсов из плана, которого в снимке нет, ему ничего не говорят и ведут в никуда. Сторож читает те же файлы открытой части,
что и ворота публикации (`tests/openpart.py`: файлы, которые лягут в снимок), и ищет в них три вида ссылок:

- номер: заглавная буква, дефис и цифры (буквы — те, что стояли в метках находок, допущений и ревью: Н, Д, И, Р, Б, П, С, Л, М, А и латинские
  M и A); буква внутри слова или имени файла номером не считается;
- порция: слово «порция» в любой форме и номер после него;
- тест-кейс: буквы «T» и «C», дефис и цифры (номер вида «из трёх частей через дефис»); буква перед ними делает слово другим («UTC-8» — часовой пояс).

Объяснение «почему» в открытой части пишется словами или номером карточки требований (FR-…, NFR-…): карточки открыты. Исключений нет. Ссылки на
сами закрытые документы и на закрытый каталог ищет закрытая часть: имён закрытых файлов в открытом тесте нет.
Образцы в самом тесте собраны из кусков: сторож читает и себя, и ни один образец не должен читаться как настоящая находка.
"""

import os
import re

import pytest

from openpart import ROOT, open_files

# ── что ищется ──────────────────────────────────────────────────
LETTERS = "НДИР" + "БПСЛМА" + "MA"                               # буквы номеров в метках находок, допущений и ревью: кириллица и латинские M, A
NUMBER = re.compile("(?<![\\w-])[" + LETTERS + "]-\\d+")
PORTION = re.compile("порци(?:я|и|ю|ей|ях|й)\\s+\\d[\\w–-]*", re.I)
TEST_CASE = re.compile("(?<![A-Za-z])T" + "C-\\d+(?:-\\d+)*")                  # образец собран из кусков: сторож читает и этот файл
KINDS = (("номер", NUMBER), ("порция", PORTION), ("тест-кейс", TEST_CASE))


def find(text):
    """[(номер строки, вид, найденное)] по тексту файла."""
    found = []
    for number, line in enumerate(text.split("\n"), 1):
        for kind, pattern in KINDS:
            found.extend((number, kind, m.group(0)) for m in pattern.finditer(line))
    return found


def read(rel):
    try:
        with open(os.path.join(ROOT, rel), "rb") as f:
            return f.read().decode("utf-8")
    except UnicodeDecodeError:
        return None                                               # картинка и прочее нетекстовое


def scan(files):
    """Находки по файлам открытой части: [(файл, строка, вид, найденное)]."""
    out = []
    for rel in files:
        text = read(rel)
        if text is not None:
            out.extend((rel, n, kind, what) for n, kind, what in find(text))
    return out


# ── сами поиски находят образцы и не трогают чистое ─────────────
NUM = "Н" + "-92"                                                 # образцы собраны из кусков: сторож читает и этот файл
PORT = "порци" + "я 24н"


def test_номер_находится_в_любой_из_букв_и_после_любой_пунктуации():
    for letter in LETTERS:
        for tail in ("92", "01", "9", "125"):
            assert find(f"# {letter}-{tail}: объяснение") == [(1, "номер", f"{letter}-{tail}")], (letter, tail)
    text = "(" + NUM + "), «" + "Д" + "-01» и " + "И" + "-9;" + "Р" + "-3, " + "П" + "-6 " + "M" + "-12."
    assert [w for _, _, w in find(text)] == [NUM, "Д" + "-01", "И" + "-9", "Р" + "-3", "П" + "-6", "M" + "-12"]
    assert find("первая\nвторая " + "Н" + "-5") == [(2, "номер", "Н" + "-5")]


def test_буква_внутри_слова_или_имени_не_номер():
    for clean in ("Н-образный", "ИИ-5", "ТЗ-Р-2", "Иван-5", "тест-Д-1", "Hbar-92", "H-92", "x" + "Н" + "-3", "Д-", "Д-а", "№ 5", "Н 92", "Н—92",
                  "Пример-1", "Б-образный", "MA-1x2", "x" + "П" + "-6", "ABC-5"):
        assert find(clean) == [], clean


def test_порция_находится_в_любой_форме_и_с_любым_номером():
    for form in ("порция", "порции", "порцию", "порцией", "порциях", "порций", "Порция", "ПОРЦИИ"):
        for number in ("24н", "20г", "3", "20а–20в"):
            assert [(k, w) for _, k, w in find(f"({form} {number})")] == [("порция", f"{form} {number}")], (form, number)


def test_обычная_порция_без_номера_не_находка():
    for clean in ("порция супа", "две порции", "порциями по пять", "порция\nбез номера", "порционно", "много порций, а не номер"):
        assert find(clean) == [], clean


def test_номер_тест_кейса_находится_в_любом_виде_и_после_любой_пунктуации():
    case = "T" + "C"
    for tail in ("1-16", "1-01", "10-3", "0-1", "7"):
        assert find(f"(см. {case}-{tail})") == [(1, "тест-кейс", f"{case}-{tail}")], tail
    assert find("# ── " + case + "-1-01: выпуск ──") == [(1, "тест-кейс", case + "-1-01")]
    assert [w for _, _, w in find(f"Вход: FR-01 ({case}-1-13, {case}-1-14, {case}-1-27).")] == [f"{case}-1-13", f"{case}-1-14", f"{case}-1-27"]
    assert find("первая\nвторая " + case + "-2-05") == [(2, "тест-кейс", case + "-2-05")]


def test_буква_перед_тест_кейсом_или_нет_цифры_это_не_номер_тест_кейса():
    case = "T" + "C"
    for clean in ("UTC-8", "UTC-5", "ETC-1", "x" + case + "-3", case, case + "-", case + "-а", case + " 1", "T-C-1", "FR-107", "NFR-01б"):
        assert find(clean) == [], clean


# ── итог: в открытой части ссылок нет ───────────────────────────
def test_файлов_открытой_части_достаточно_и_главные_на_месте():
    files = open_files()
    assert len(files) > 150, f"проверено слишком мало файлов ({len(files)}): список файлов не прочитан"
    assert {"tools/flyarchive", "tools/index_more.py", "dsh-plugin/lib/index.js", "tests/test_open_part_no_closed_refs.py", "docs/operations.md"} <= set(files)


def test_в_открытой_части_нет_номеров_находок_допущений_и_ревью_номеров_порций_и_тест_кейсов():
    left = scan(open_files())
    if left:
        shown = [f"{rel}:{n}: {kind}: {what}" for rel, n, kind, what in left]
        pytest.fail(f"ссылок на закрытую кухню в открытой части: {len(left)}\n" + "\n".join(shown[:80]) + ("\n…" if len(shown) > 80 else ""))
