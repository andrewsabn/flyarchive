"""Чужое имя в тестах: приставка переменных, каталог, служба и заголовок другой программы, которые система не читает и не принимает.

Свойство общее: переменная окружения с чужой приставкой не читается, чужой каталог в домашнем не подхватывается, чужой заголовок
не принимается, чужая служба не учитывается. Образец — выдуманная программа «otherapp». Тесты, которые берут имена отсюда, помечены
`foreign_name`; значения можно подменить переменными окружения FLYARCHIVE_TEST_FOREIGN_NAME и FLYARCHIVE_TEST_FOREIGN_KEY, и тогда те же
тесты проверяют те же свойства на другом имени (так одни и те же тесты прогоняют на любом имени: свойство не зависит от того, каким оно выбрано).
"""
import os

NAME_ENV = "FLYARCHIVE_TEST_FOREIGN_NAME"
KEY_ENV = "FLYARCHIVE_TEST_FOREIGN_KEY"
NAME = os.environ.get(NAME_ENV) or "otherapp"                  # имя чужой программы: каталог в домашнем, имя службы
KEY = os.environ.get(KEY_ENV) or "OTHERLIB_API_KEY"            # переменная ключа модели, которую знает чужая библиотека, но не проект
PREFIX = NAME.upper() + "_"                                    # приставка чужих переменных окружения
HOME_VARIABLE = PREFIX + "HOME"                                # чужая переменная каталога архива
HEADER_PREFIX = "X-" + NAME.capitalize() + "-"                 # приставка чужих служебных заголовков
UNIT = NAME + "-gateway.service"                               # чужая служба шлюза
